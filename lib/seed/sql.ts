// Renders a Dataset as idempotent SQL inserts (supabase/seed.sql).
import { KEY_COLUMN, TABLE_ORDER, type Dataset } from '@/lib/db/types';

const JSONB_COLUMNS = new Set([
  'settings.value', 'sku_configs.variant_attrs', 'sku_configs.overrides', 'shelf_observations.attributes', 'plays.assumption_overrides',
  'scenarios.limits', 'scenarios.overrides', 'market_watch_notes.flags', 'setup_snapshots.snapshot', 'orders.lines',
]);

function str(s: string): string {
  return `'${s.replace(/'/g, "''")}'`;
}

function arrayLiteral(xs: unknown[]): string {
  const inner = xs.map((x) => `"${String(x).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`).join(',');
  return str(`{${inner}}`);
}

export function literal(table: string, column: string, v: unknown): string {
  if (v === null || v === undefined) return 'null';
  if (JSONB_COLUMNS.has(`${table}.${column}`)) return `${str(JSON.stringify(v))}::jsonb`;
  if (Array.isArray(v)) return arrayLiteral(v);
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'object') return `${str(JSON.stringify(v))}::jsonb`;
  return str(String(v));
}

export function datasetToSql(d: Dataset): string {
  const out: string[] = ['-- Generated by scripts/gen-seed-sql.ts from /seed. Re-run: npm run seed:sql', 'begin;'];
  for (const t of TABLE_ORDER) {
    const rows = d[t] as unknown as Record<string, unknown>[];
    if (!rows.length) continue;
    out.push(`\n-- ${t} (${rows.length})`);
    const key = KEY_COLUMN[t] ?? 'id';
    for (const r of rows) {
      // replaced_by is a self-reference; seed rows are all current so it is always null here.
      const cols = Object.keys(r);
      out.push(
        `insert into ${t} (${cols.join(', ')}) values (${cols.map((c) => literal(t, c, r[c])).join(', ')}) on conflict (${key}) do nothing;`,
      );
    }
  }
  out.push('commit;');
  return out.join('\n') + '\n';
}
